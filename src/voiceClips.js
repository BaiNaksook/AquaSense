// ===== ประกอบประโยค =====
// ประโยค = { text: ข้อความสำหรับเสียงอ่านอัตโนมัติ, clips: [id ของไฟล์เสียง] }
export const line = (text, clips) => ({ text, clips })

// ตัวเลข 0–100 → ลำดับคลิป เช่น 23 → [ยี่สิบ, สาม], 21 → [ยี่สิบ, เอ็ด]
export function numberClips(n) {
  const v = Math.max(0, Math.min(100, Math.round(n)))
  if (v === 100) return ['n-100']
  if (v < 10) return [`n-${v}`]
  const tens = Math.floor(v / 10) * 10
  const unit = v % 10
  if (unit === 0) return [`n-${tens}`]
  return [`n-${tens}`, unit === 1 ? 'n-ed' : `n-${unit}`]
}

export function dayClip(dateStr, todayStr) {
  if (dateStr === todayStr) return 'd-today'
  const d = new Date(`${dateStr}T00:00:00`)
  const t = new Date(`${todayStr}T00:00:00`)
  if (Math.round((d - t) / 864e5) === 1) return 'd-tomorrow'
  return `d-${d.getDay()}`
}

export const timeClip = (hhmm) => `t-${hhmm.slice(0, 2)}`
