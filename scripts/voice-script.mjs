// สร้างบทอัดเสียง docs/voice-recording.md จาก src/voiceClips.js — npm run voice:script
import { writeFileSync } from 'node:fs'
import { CLIP_GROUPS, CLIP_TEXT } from '../src/voiceClips.js'

const total = Object.keys(CLIP_TEXT).length
let md = `# บทอัดเสียง SaltSense

เสียงที่เว็บใช้พูดกับเกษตรกร อัดครั้งเดียวใช้ได้ตลอด (${total} ไฟล์ ประมาณ 30–45 นาที)

## วิธีอัด
1. ห้องเงียบ ปิดพัดลม/แอร์ ใช้แอปอัดเสียงในมือถือได้เลย ถือมือถือห่างปากประมาณ 1 คืบ
2. พูดน้ำเสียงเป็นกันเอง เหมือนบอกลุงป้าข้างบ้าน ไม่ต้องอ่านแบบประกาศ ไม่ต้องรีบ
3. **1 ประโยค = 1 ไฟล์** เว้นเงียบก่อนและหลังพูดประมาณครึ่งวินาที (ระบบตัดให้เอง)
4. **ตั้งชื่อไฟล์ตามช่อง "ชื่อไฟล์"** เช่น \`w-safe.m4a\` นามสกุลอะไรก็ได้ (m4a, mp3, wav)
5. ตัวเลขและวัน/เวลา จะถูกนำไปต่อกับประโยคอื่น ให้พูดระดับเสียงเดียวกันทุกไฟล์ ไม่ขึ้นเสียงท้ายคำ
6. อัดไม่ครบก็ใช้ได้ — ประโยคไหนยังไม่มีไฟล์ ระบบจะใช้เสียงอ่านอัตโนมัติแทน

## ใส่ไฟล์เข้าระบบ
\`\`\`bash
# วางไฟล์ทั้งหมดในโฟลเดอร์ voice-raw/ ที่รากโปรเจกต์ แล้วรัน
npm run voice:process
# พูดช้าไป อยากเร่งนิดหน่อย
npm run voice:process -- voice-raw --tempo 1.05
\`\`\`
ระบบจะตัดช่วงเงียบ ลดเสียงรบกวน ปรับความดังให้เท่ากัน แล้วบันทึกเป็น \`public/voice/*.mp3\`
พร้อมบอกว่ายังขาดไฟล์ไหน จากนั้น commit โฟลเดอร์ \`public/voice\` แล้ว deploy

`
for (const group of CLIP_GROUPS) {
  md += `## ${group.title}\n\n| ✓ | ชื่อไฟล์ | พูดว่า |\n|---|---|---|\n`
  for (const [id, text] of Object.entries(group.clips)) md += `| ☐ | \`${id}\` | ${text} |\n`
  md += '\n'
}
md += `## ตัวอย่างการต่อประโยค
- "ความเค็มตอนนี้" + "ยี่สิบ" + "สาม" + "ดีกรี" + "ยังไม่พร้อมเก็บครับ"
- "วันนี้มีโอกาสฝนตก" + "หกสิบ" + "ห้า" + "เปอร์เซ็นต์" + "ครับ"
- "ฝนน่าจะเริ่มราว" + "หนึ่งทุ่ม"
`
writeFileSync('docs/voice-recording.md', md)
console.log(`เขียน docs/voice-recording.md แล้ว (${total} ไฟล์)`)
